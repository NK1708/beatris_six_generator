import React from "react";
import { act, create } from "react-test-renderer";
import { expect, it } from "vitest";
import { storyStateSchema } from "@bearridge/shared";
import { StoryStateHolder, displayStoryStateValue } from "./components/StoryStateHolder.js";
import { TargetStateFields, TargetComparisonOverview } from "./components/TargetStateFields.js";
import { targetStateDiff } from "./targetStateComparison.js";
const characters = [{ id: "bird-id", name: "Birdman", outfits: [] }, { id: "web-id", name: "Webster", outfits: [] }];
const original = storyStateSchema.parse({ sceneId: "scene", time: { description: "Morning" }, characters: { "web-id": { present: false, heldProps: ["arbitrary prop"] } }, props: { cup: { holderCharacterId: "web-id", location: "shelf", state: "full" } } });
it("selects project characters by name, preserving historical IDs until explicit change and allowing no owner", async () => {
    let value = "historical-id";
    let renderer;
    await act(async () => { renderer = create(React.createElement(StoryStateHolder, { value, characters, onChange: next => { value = next; } })); });
    expect(renderer.root.findByType("select").props.value).toBe("historical-id");
    const options = renderer.root.findAllByType("option");
    expect(options.map(option => option.children.join(""))).toEqual(["Без владельца", "Неизвестный владелец (historical-id)", "Birdman", "Webster"]);
    expect(value).toBe("historical-id");
    await act(async () => renderer.root.findByType("select").props.onChange({ target: { value: "bird-id" } }));
    expect(value).toBe("bird-id");
    await act(async () => renderer.root.findByType("select").props.onChange({ target: { value: "" } }));
    expect(value).toBeUndefined();
    renderer.unmount();
});
it("transfers only the holder ID without changing presence, heldProps, Cast input or source snapshot", async () => {
    const baseline = JSON.stringify(original);
    const source = { status: "AVAILABLE", document: original, label: "Snapshot", note: "Historical" };
    const castIds = ["web-id"];
    let document = structuredClone(original);
    let renderer;
    const element = (readOnly = false) => React.createElement(TargetStateFields, { document, source, characters, castIds, readOnly, onChange: next => { document = next; } });
    await act(async () => { renderer = create(element()); });
    const holder = renderer.root.findByType(StoryStateHolder);
    await act(async () => holder.props.onChange("bird-id"));
    expect(document.props.cup.holderCharacterId).toBe("bird-id");
    expect(document.characters).toEqual(original.characters);
    expect(castIds).toEqual(["web-id"]);
    expect(JSON.stringify(original)).toBe(baseline);
    expect(targetStateDiff(source, document).filter(row => row.status !== "unchanged")).toEqual([{ path: ["props", "cup", "holderCharacterId"], before: "web-id", after: "bird-id", status: "changed" }]);
    await act(async () => renderer.update(element(true)));
    expect(renderer.root.findByProps({ className: "targetFullFields" }).props.disabled).toBe(true);
    renderer.unmount();
});
it("formats holder diffs by name while keeping raw values and arbitrary strings intact", async () => {
    const source = { status: "AVAILABLE", document: original, label: "Snapshot", note: "Historical" };
    const document = structuredClone(original);
    document.props.cup.holderCharacterId = "bird-id";
    let renderer;
    await act(async () => { renderer = create(React.createElement(TargetComparisonOverview, { source, document, characters })); });
    const output = JSON.stringify(renderer.toJSON());
    expect(output).toContain("Webster");
    expect(output).toContain("Birdman");
    expect(displayStoryStateValue("missing-id", ["props", "cup", "holderCharacterId"], characters)).toBe("Неизвестный владелец (missing-id)");
    expect(displayStoryStateValue("web-id", ["props", "cup", "location"], characters)).toBe("web-id");
    expect(document.props.cup.holderCharacterId).toBe("bird-id");
    renderer.unmount();
});
